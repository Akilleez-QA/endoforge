import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { performance } from 'node:perf_hooks';
import { IsolatePool } from '../../core/runtime/isolate-pool.mjs';
import { runNeed } from '../../core/runtime/x1/pipeline.mjs';
const [source, wasm, id, spawnLog] = process.argv.slice(2);
const here = fileURLToPath(new URL('./', import.meta.url)), root = mkdtempSync(join(tmpdir(), 'p53-gen-'));
const wasmPath = join(root, 'kernel.b64');
writeFileSync(wasmPath, wasm);
const env = { ...process.env, ENDOFORGE_CODEX_CMD: JSON.stringify([process.execPath, join(here, 'replay-codex.mjs')]), CODEX_HOME: join(root, 'home'), ENDOFORGE_ASC_CMD: join(here, 'replay-asc.mjs'), ENDOFORGE_CODEX_TERSE: 'scalar', ENDOFORGE_CODEX_TEST_DOUBLE: '1', ENDOFORGE_SELF_CHECK: '0', P53_REPLAY: source, P53_WASM: wasmPath, P53_SPAWN_LOG: spawnLog };
const pool = new IsolatePool({ hostPort: fileURLToPath(new URL('../../core/runtime/x1/host.mjs', import.meta.url)), size: 1, isolation: 'thread', prewarm: true });
await pool.ready?.();
const begin = performance.now();
const result = await runNeed({ need: 'Replayed; no model.', directory: join(root, id), pool, env });
const wallMs = performance.now() - begin;
await pool.close();
rmSync(root, { recursive: true, force: true });
console.log(JSON.stringify({ promoted: result.promoted, wallMs, timings: result.timings, spawns: readFileSync(spawnLog, 'utf8').trim().split('\n') }));
