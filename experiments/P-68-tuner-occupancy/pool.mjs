import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { availableParallelism } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const [output, ...rest] = process.argv.slice(2);
const flag = (name, fallback) => { const hit = rest.find(item => item.startsWith(`--${name}=`)); return hit ? hit.slice(name.length + 3) : fallback; };
const repo = resolve(flag('repo', new URL('../..', import.meta.url).pathname));
const from = path => import(pathToFileURL(join(repo, path)).href);
const { IsolatePool } = await from('core/runtime/isolate-pool.mjs');
const { defaultWidth, plan, probe } = await from('core/runtime/capacity/index.mjs');
const { fixture, hostPort } = await from('core/runtime/test/fixtures/ledger-fixture.mjs');
mkdirSync(output, { recursive: true });
const SECONDS = Number(flag('seconds', 60)), DEMAND = Number(flag('demand', 64)), LOADED = 16;
const load = () => Number(readFileSync('/proc/loadavg', 'utf8').split(' ')[0]);
const psi = () => Number(readFileSync('/proc/pressure/cpu', 'utf8').match(/^some avg10=([\d.]+)/m)[1]);
const own = '/sys/fs/cgroup' + readFileSync('/proc/self/cgroup', 'utf8').split('\n').find(line => line.startsWith('0::')).slice(3);
const usage = () => Number(readFileSync(`${own}/cpu.stat`, 'utf8').match(/^usage_usec (\d+)/m)[1]);
const sleep = ms => new Promise(done => setTimeout(done, ms));
const cleanups = [];
const t = { after: fn => cleanups.push(fn) };
const { job } = await fixture(t);
const sizes = { plan: defaultWidth(), old: availableParallelism() };
const order = flag('order', 'forward') === 'reverse' ? ['old', 'plan'] : ['plan', 'old'];
const label = flag('label', 'round1');
const file = join(output, `pool-${label}-${process.versions.node}.json`);
const rows = existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')).rows : [];
for (const arm of order) {
  const started0 = Date.now();
  while ((load() > LOADED || psi() > 5) && Date.now() - started0 < 20 * 60000) await sleep(15000);
  const loadStart = load(), psiStart = psi();
  const pool = new IsolatePool({ hostPort, size: sizes[arm] });
  await pool.ready();
  await Promise.all(Array.from({ length: sizes[arm] }, () => pool.run(job(['pass', 'effects']))));
  let done = 0, failed = 0, peakRss = 0;
  const stopAt = performance.now() + SECONDS * 1000, cpu0 = usage(), started = performance.now();
  const rss = setInterval(() => { try { peakRss = Math.max(peakRss, Number(readFileSync(`${own}/memory.current`, 'utf8')) / 1048576); } catch {} }, 1000);
  await Promise.all(Array.from({ length: DEMAND }, async () => { while (performance.now() < stopAt) { const result = await pool.run(job(['pass', 'effects'])).catch(error => ({ status: 'error', reason: error.message })); if (result.report) done += 1; else failed += 1; } }));
  const wall = performance.now() - started, cpu = (usage() - cpu0) / 1e6;
  clearInterval(rss);
  await pool.close();
  const loadAtStop = load();
  const cool = Date.now();
  while ((load() > LOADED || psi() > 5) && Date.now() - cool < 180000) await sleep(5000);
  const row = { arm, size: sizes[arm], seconds: SECONDS, demand: DEMAND, jobs: done, failed, perSecond: +(done / wall * 1000).toFixed(1), cpuMsPerJob: +(cpu * 1000 / done).toFixed(2), busyCpus: +(cpu / wall * 1000).toFixed(2), peakCgroupMb: Math.round(peakRss), loadStart, psiStart, loadAtStop, loadEnd: load(), psiEnd: psi() };
  row.quiet = row.loadStart <= LOADED && row.loadEnd <= LOADED && row.psiStart <= 5 && row.psiEnd <= 5;
  rows.splice(0, rows.length, ...rows.filter(item => item.arm !== arm), row);
  console.log(JSON.stringify(row));
  writeFileSync(file, JSON.stringify({ node: process.versions.node, probe: probe(), plan: plan(), sizes, rows }, null, 1));
}
for (const fn of cleanups) fn();
process.exit(0);
